ROW = 5      # 字形高度
COL = 5      # 字形宽度

_FONTS = {
    'ascii':   {'fill': '#', 'desc': '井号, 终端最稳'},
    'block':   {'fill': '█', 'desc': '实心方块, 最醒目'},
    'outline': {'fill': '█', 'outline': True, 'desc': '空心轮廓'},
    'shadow':  {'fill': '█', 'shadow': '░', 'desc': '实心 + 右下投影'},
    'dot':     {'fill': '•', 'desc': '圆点'},
    'slant':   {'fill': '█', 'slant': True, 'desc': '斜体'},
}
DEFAULT_FONT = 'ascii'


def _load(blob):
    out = {}
    for line in blob.strip().splitlines():
        parts = line.split()
        if not parts:
            continue
        ch, rows = parts[0], parts[1:]
        assert len(rows) == ROW, f'{ch!r} 行数 {len(rows)} != {ROW}'
        assert all(len(r) == COL for r in rows), f'{ch!r} 列宽不对'
        out[ch] = rows
    return out


